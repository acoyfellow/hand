const tileLabel = (h: H, text: string, onNight: boolean): Html => h.span([h.Class(`${TILE_LABEL} ${onNight ? 'text-[#a1a1a6]' : 'text-[#5f5f65]'}`)], [text]);

const AGENT_NAMES = ['ada', 'bix', 'cyd', 'dot', 'eli', 'fay'];

const agents = (h: H, model: Model): Html =>
  h.div(
    [h.Class(PAPER)],
    [
      h.div(
        [h.Class('grid grid-cols-[repeat(3,64px)] gap-3.5'), h.Role('img'), h.AriaLabel('Six generated hands, one per agent name')],
        AGENT_NAMES.map((name) => {
          const agent = Mark.agent(name);
          return h.div(
            [h.Key(`${name}-${model.live}`), h.Class('size-16'), ...(model.live ? [h.OnMount(MarkArt({ options: agent.shape, accent: agent.accent, size: 64 }))] : [])],
            [],
          );
        }),
      ),
      tileLabel(h, 'every name gets its own hand', false),
    ],
  );

